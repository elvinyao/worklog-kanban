test('an already-open discard prompt cannot close the dialog during saving',async({page})=>{
 await page.goto(board);await page.getByRole('button',{name:'新建卡片',exact:true}).click();
 await page.getByLabel('共享标题').fill('保存中的卡片');await page.getByRole('button',{name:'关闭详情'}).click();
 let release:()=>void=()=>{};const gate=new Promise<void>(resolve=>{release=resolve;});
 await page.route('**/api/cards',async route=>{await gate;await route.continue();});
 try{await page.getByRole('button',{name:'创建卡片',exact:true}).click();await expect(page.getByRole('button',{name:'正在保存…'})).toBeVisible();await expect(page.getByRole('button',{name:'放弃修改并关闭'})).toBeDisabled();}
 finally{release();}
 await expect(page.getByRole('dialog')).toHaveCount(0);
});
